        r = res0['models'][k]; P = build_pred(nets[k], Bte, r['cqr_correction_bits'], r['spread_thr95'], res0['maha_thr95'], M['maha'][0], M['maha'][1], d['X1'], k); real[k] = mae(P['Nraw'].cpu().numpy())
