    Bte = to_dev(d, st); out = dict(NOT_CITABLE='until a blind bug review', code_sha256=CODE_SHA256)
    def mae(q, rep=None):
        e = np.abs(q[:, 2] - YN); x, _ = B.pm(e, six); r = B.mean(x); a1, _ = B.pm(np.abs(A1 - YN), six & np.isfinite(A1)); return dict(MAE=r, ratio_to_A1_point=float(x.mean() / a1.mean()))
    ytr = Btr['Y'][:, [0, 2]]; yva = Bva['Y'][:, [0, 2]]
