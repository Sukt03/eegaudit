IXN = None
def boot_idx(nP):
    g = torch.Generator(device=DEV); g.manual_seed(20261124); return torch.randint(nP, (10000, nP), generator=g, device=DEV)


class Bt:
    """Participant-level statistics with ONE index tensor."""
    def __init__(self, plist, pid): self.pl = plist; self.pid = torch.as_tensor([plist.index(p) for p in pid], device=DEV); self.nP = len(plist); self.IX = boot_idx(self.nP)
    def pm(self, v, mask):                        # per-participant mean over the masked cells; NaN where a participant has none
        v = torch.as_tensor(v, dtype=torch.float64, device=DEV); mk = torch.as_tensor(mask, device=DEV); S = torch.zeros(self.nP, **T64).index_add_(0, self.pid[mk], v[mk]); C = torch.zeros(self.nP, **T64).index_add_(0, self.pid[mk], torch.ones(int(mk.sum()), **T64))
        return S / C.clamp_min(1), C
    def mean(self, x, w=None):                    # cohort mean of per-participant values x (nP,), optional 0/1 weights; ratio over resampled participants
        w = torch.ones_like(x) if w is None else w; num = (x * w)[self.IX].sum(1); den = w[self.IX].sum(1); r = num / den.clamp_min(1e-12); ok = den > 0
        pt = float((x * w).sum() / w.sum().clamp_min(1e-12)); q = torch.quantile(r[ok], torch.tensor([.025, .975], **T64)).tolist() if int(ok.sum()) > 100 else [float('nan')] * 2; return dict(value=pt, ci95=q, n_participants=int(w.sum()))
    def ratio(self, num, den):                    # ratio of cohort means
        r = num[self.IX].mean(1) / den[self.IX].mean(1); return dict(value=float(num.mean() / den.mean()), ci95=torch.quantile(r, torch.tensor([.025, .975], **T64)).tolist())


def reading_upper(ci, bound): return 'PASS' if ci[1] <= bound else ('FAIL' if ci[0] > bound else 'UNDECIDED')
def reading_lower(ci, bound): return 'PASS' if ci[0] >= bound else ('FAIL' if ci[1] < bound else 'UNDECIDED')
def reading_inside(ci, lo, hi): return 'PASS' if (ci[0] >= lo and ci[1] <= hi) else ('FAIL' if (ci[1] < lo or ci[0] > hi) else 'UNDECIDED')


def cellinfo(d):
    m = lambda k: col(d, k); rho, f, a, b = m('rho'), m('f'), m('a'), m('b')
    six = np.isin(np.round(rho, 3), [0.25, 0.5]) & np.isin(np.round(f, 3), [0.25, 0.5, 0.75]) & (a > 0) & (b > 0)
    return dict(six=six, null=(a == 0) & (b == 0), oc=(a == 0) & (b > 0), f0=(b == 0) & (a > 0), r25=np.isclose(rho, 0.25) & (f > 0.2) & (f < 0.8), r5=np.isclose(rho, 0.5) & (f > 0.2) & (f < 0.8), r9=np.isclose(rho, 0.9) & (f > 0.2) & (f < 0.8))


def eval_family(fam, d, P, thr, name):
    """d: test shards of one family; P: dict(Nraw (m,5), Ncal (m,5), Oraw, Ocal, med spread, flag). Returns the F-criteria with readings."""
    ci = cellinfo(d); YN = d['Y'][:, 0]; YO = d['Y'][:, 2]; A0 = d['Y'][:, 4]; A1 = d['BL'][:, 0]; A4 = d['BL'][:, 2]; B = Bt(TEST, d['pid']); R = dict(family=fam, model=name); six = ci['six']
    q = P['Ncal'].cpu().numpy(); qo = P['Ocal'].cpu().numpy(); err = np.abs(q[:, 2] - YN); cov = ((YN >= q[:, 0]) & (YN <= q[:, 4])).astype(float); width = q[:, 4] - q[:, 0]
    # F1: six cells
    cells = {}; f1 = []; f1s = []
    for rho in (0.25, 0.5):
        for f in (0.25, 0.5, 0.75):
            mk = six & np.isclose(col(d, 'rho'), rho) & np.isclose(col(d, 'f'), f); x, C = B.pm(err, mk); sg, _ = B.pm(q[:, 2] - YN, mk)
            e = B.mean(x); e['reading'] = reading_upper(e['ci95'], 0.03); s_ = B.mean(sg); s_['reading_inside_pm0.03'] = reading_inside(s_['ci95'], -0.03, 0.03)
            cells[f'rho{rho}_f{f}'] = dict(MAE=e, signed_error=s_, mean_truth=float(YN[mk].mean()), mean_q50=float(q[mk, 2].mean()), n_cells=int(mk.sum()))
            f1.append(e['reading']); f1s.append(s_['reading_inside_pm0.03'])
    R['F1_cells'] = cells; R['F1'] = 'PASS' if f1.count('PASS') >= 5 else ('FAIL' if f1.count('FAIL') >= 2 else 'UNDECIDED'); R['F1_signed_descriptive'] = 'PASS' if f1s.count('PASS') >= 5 else ('FAIL' if f1s.count('FAIL') >= 2 else 'UNDECIDED')
    # F2: coverage pooled over the six cells
    x, _ = B.pm(cov, six); R['F2_coverage'] = B.mean(x); R['F2_coverage']['reading'] = reading_inside(R['F2_coverage']['ci95'], 0.85, 0.95)
    R['F2_strata_descriptive'] = {f'rho{r}': float(cov[six & np.isclose(col(d, 'rho'), r)].mean()) for r in (0.25, 0.5)}
    # F3: null cells
    nm = ci['null']; qn = P['Ncal'].cpu().numpy(); cont = ((qn[:, 0] <= 0) & (qn[:, 4] >= 0)).astype(float); x, _ = B.pm(cont, nm); R['F3_null_interval_contains_0'] = B.mean(x); R['F3_null_interval_contains_0']['reading'] = reading_lower(R['F3_null_interval_contains_0']['ci95'], 0.88)
    R['F3_null_n_cells'] = int(nm.sum()); R['F3_null_point_fraction'] = float(cont[nm].mean()); R['F3_extra_null_abs_median_le_0.02'] = float((np.abs(qn[nm, 2]) <= 0.02).mean()); R['F3_extra_ocular_only_median_le_0.02'] = float((qn[ci['oc'], 2] <= 0.02).mean())
    R['F3_extra_ocular_only_interval_contains_0'] = float(cont[ci['oc']].mean())
    # F4: Y_O on the F1 grid where Y_O >= 0.05 (participant seed-mean)
    erro = np.abs(qo[:, 2] - YO); f4 = []; R['F4_cells'] = {}
    for rho in (0.25, 0.5):
        for f in (0.25, 0.5, 0.75):
            mk = six & np.isclose(col(d, 'rho'), rho) & np.isclose(col(d, 'f'), f); xo, _ = B.pm(YO, mk); xe, _ = B.pm(erro, mk); w = (xo >= 0.05).double()
            if int(w.sum()) < 3: r_ = dict(value=float('nan'), ci95=[float('nan')] * 2, n_participants=int(w.sum()), reading='UNDECIDED (fewer than 3 participants with Y_O >= 0.05)')
            else: r_ = B.mean(xe, w); r_['reading'] = reading_upper(r_['ci95'], 0.03)
            R['F4_cells'][f'rho{rho}_f{f}'] = r_; f4.append(r_['reading'].split(' ')[0])
    R['F4'] = 'PASS' if f4.count('PASS') >= 5 else ('FAIL' if f4.count('FAIL') >= 2 else 'UNDECIDED')
    # F5: widths and coverage at RHO 0.9
    w25, _ = B.pm(width, ci['r25']); w9, _ = B.pm(width, ci['r9']); rr = B.ratio(w9, w25); c9, _ = B.pm(cov, ci['r9']); cc = B.mean(c9)
    R['F5_width_ratio_rho0.9_over_0.25'] = dict(**rr, reading=reading_lower(rr['ci95'], 1.5)); R['F5_coverage_rho0.9'] = dict(**cc, reading=reading_lower(cc['ci95'], 0.85))
    R['F5_median_width'] = dict(rho0p25=float(np.median(width[ci['r25']])), rho0p9=float(np.median(width[ci['r9']])))
    R['F5'] = 'PASS' if (R['F5_width_ratio_rho0.9_over_0.25']['reading'] == 'PASS' and R['F5_coverage_rho0.9']['reading'] == 'PASS') else ('FAIL' if 'FAIL' in (R['F5_width_ratio_rho0.9_over_0.25']['reading'], R['F5_coverage_rho0.9']['reading']) else 'UNDECIDED')
    # F6: against the better of A1 and A4 (family-level choice by point MAE, same six cells)
    ok6 = six & np.isfinite(A1) & np.isfinite(A4); em, _ = B.pm(err, ok6); e1, _ = B.pm(np.abs(A1 - YN), ok6); e4, _ = B.pm(np.abs(A4 - YN), ok6); e0, _ = B.pm(np.abs(A0 - YN), six); best = 'A1' if float(e1.mean()) <= float(e4.mean()) else 'A4'; eb = e1 if best == 'A1' else e4
    rr6 = B.ratio(em, eb); R['F6'] = dict(better_baseline=best, MAE_model=float(em.mean()), MAE_A1=float(e1.mean()), MAE_A4=float(e4.mean()), MAE_A0=float(e0.mean()), ratio_to_better=rr6, reading=reading_upper(rr6['ci95'], 0.75))
