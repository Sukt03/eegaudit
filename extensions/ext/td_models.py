def col(d, k): return d['META'][:, d['mn'].index(k)]


def audit_prior(d, plist, kind):
    """Leakage re-read of the training data: participants, prior parameters (no held-out family value may occur)."""
    assert set(d['pid'].tolist()) <= set(plist), (kind, 'participant outside split')
    assert (col(d, 'fam') == 1).all(); assert (col(d, 'w0') >= 20).all(); assert set(col(d, 'wd').tolist()) <= {8.0, 16.0}
    assert (col(d, 'r_n') <= 2).all() and (col(d, 'r_e') <= 2).all(); r = col(d, 'rho'); assert not ((r > 0.35) & (r < 0.65)).any(); assert (col(d, 'eye_class') == 0).all()
    return dict(kind=kind, n_cells=int(len(d["pid"])), participants=sorted(set(d["pid"].tolist())), w0_min=float(col(d, "w0").min()), widths=sorted(set(col(d, "wd").tolist())), max_rank=float(max(col(d, "r_n").max(), col(d, "r_e").max())), rho_band_0p35_0p65_cells=0, eye_class_random_only=True)


class Std:
    """Standardisation fitted on training cells only."""
    def __init__(self, d):
        X = torch.as_tensor(d['X1'], dtype=torch.float32, device=DEV); self.mx, self.sx = X.mean(0), X.std(0) + 1e-6
        P = torch.as_tensor(d['PCX'], dtype=torch.float32, device=DEV); self.mp, self.sp = P.mean(0), P.std(0) + 1e-6
        T = torch.as_tensor(d['TOK'][::4], dtype=torch.float32, device=DEV); nu = torch.as_tensor(d['NUSE'][::4], device=DEV); mk = (torch.arange(T.shape[1], device=DEV)[None] < nu[:, None])[..., None].float()
        self.mt = (T * mk).sum((0, 1)) / mk.sum(); self.st = (((T - self.mt) ** 2 * mk).sum((0, 1)) / mk.sum()).sqrt() + 1e-6
    def x1(self, X): return ((torch.as_tensor(X, dtype=torch.float32, device=DEV) - self.mx) / self.sx).clamp(-10, 10)
    def pcx(self, P): return ((torch.as_tensor(P, dtype=torch.float32, device=DEV) - self.mp) / self.sp).clamp(-10, 10)
    def tok(self, T): return ((torch.as_tensor(T, dtype=torch.float32, device=DEV) - self.mt) / self.st).clamp(-10, 10)


def to_dev(d, st):
    return dict(X1=st.x1(d['X1']), PCX=st.pcx(d['PCX']), TOK=torch.cat([st.tok(d['TOK'][i:i + 256]).half() for i in range(0, len(d['TOK']), 256)]), NUSE=torch.as_tensor(d['NUSE'], device=DEV), Y=torch.as_tensor(d['Y'], dtype=torch.float32, device=DEV),
                joint=torch.as_tensor(d['X1'][:, :2], dtype=torch.float32, device=DEV), st=st)


# ---------------------------------------------------------------- nets
def mono(o):
    o = o.view(o.shape[0], -1, 5); sp = Fn_.softplus; q50 = o[..., 2]; q25 = q50 - sp(o[..., 1]); q05 = q25 - sp(o[..., 0]); q75 = q50 + sp(o[..., 3]); q95 = q75 + sp(o[..., 4]); return torch.stack([q05, q25, q50, q75, q95], -1)


def pinball(q, y):                       # q (B, k, 5), y (B, k) -> (k,) mean over batch of the sum over levels
    e = y[..., None] - q; return torch.maximum(QS * e, (QS - 1) * e).sum(-1).mean(0)


class D1Net(nn.Module):
    def __init__(self, nx, k=2):
        super().__init__(); self.c = nn.Sequential(nn.Conv1d(3, 8, 5, padding=2), nn.GELU(), nn.Conv1d(8, 8, 5, stride=2, padding=2), nn.GELU(), nn.Flatten(), nn.Linear(8 * 32, 32), nn.GELU())
        self.s = nn.Sequential(nn.Linear(nx, 64), nn.GELU()); self.h = nn.Sequential(nn.Dropout(0.1), nn.Linear(96, 64), nn.GELU(), nn.Linear(64, 5 * k))
    def forward(self, b): return mono(self.h(torch.cat([self.c(b['PCX']), self.s(b['X1'])], 1)))


class D2Net(nn.Module):
    def __init__(self, nt=76, k=3, d=64):
        super().__init__(); self.inp = nn.Linear(nt, d); L = nn.TransformerEncoderLayer(d, 4, 128, dropout=0.1, batch_first=True, norm_first=True); self.enc = nn.TransformerEncoder(L, 2, enable_nested_tensor=False)
        self.h = nn.Sequential(nn.Linear(2 * d + 3, 64), nn.GELU(), nn.Linear(64, 5 * k))
    def forward(self, b):
        T = b['TOK'].float(); n = T.shape[1]; valid = torch.arange(n, device=T.device)[None] < b['NUSE'][:, None]
        h = self.enc(self.inp(T), src_key_padding_mask=~valid); v = valid[..., None].float(); mean = (h * v).sum(1) / v.sum(1); mx = h.masked_fill(~valid[..., None], -1e4).max(1).values
        side = torch.cat([(b['NUSE'].float() / 480.0)[:, None], b['joint'] / SC], 1); return mono(self.h(torch.cat([mean, mx, side], 1)))


def sub(b, ix): return {k: (v[ix] if torch.is_tensor(v) and v.shape[:1] == b['Y'].shape[:1] else v) for k, v in b.items()}


@torch.no_grad()
def predict(net, b, bs=64):
    net.eval(); out = []
    for i in range(0, len(b['Y']), bs): out.append(net(sub(b, slice(i, i + bs))))
    return torch.cat(out)


def fit_member(kind, btr, bva, ytr, yva, seed, epochs, patience, lr, bs, wd=1e-2, noise=None):
    """One member. ytr (N, k) in bits; loss = pinball on y / SC. Early stopping on validation pinball (sum over tasks 0 and 1 = N and O)."""
    torch.manual_seed(seed); k = ytr.shape[1]; net = (D1Net(btr['X1'].shape[1], k) if kind == 'D1' else D2Net(k=k)).to(DEV); opt = torch.optim.AdamW(net.parameters(), lr=lr, weight_decay=wd)
    best, bstate, bad = 1e9, None, 0; N = len(ytr); g = torch.Generator(device=DEV); g.manual_seed(seed)
    for ep in range(epochs):
        net.train(); perm = torch.randperm(N, generator=g, device=DEV)
        for i in range(0, N, bs):
            ix = perm[i:i + bs]; q = net(sub(btr, ix)); loss = pinball(q, ytr[ix] / SC).sum(); opt.zero_grad(); loss.backward(); nn.utils.clip_grad_norm_(net.parameters(), 5.0); opt.step()
        v = float(pinball(predict(net, bva), yva / SC)[:2].sum())
        if v < best - 1e-4: best, bad = v, 0; bstate = {kk: vv.clone() for kk, vv in net.state_dict().items()}
        else:
            bad += 1
            if bad >= patience: break
    net.load_state_dict(bstate); return net, best, ep + 1


def ens_predict(nets, b):
    P = torch.stack([predict(n, b) for n in nets]); return P.mean(0), P[..., 0, 2].std(0)                    # ensemble quantiles (mean of members, (m, k, 5)), spread of the members' N-medians (m,) in label/SC units


# ---------------------------------------------------------------- calibration, abstention
def cqr_correction(q, y, alpha=0.1):
    """q (m, 5) uncalibrated quantiles, y (m,): split-conformal CQR on the [q05, q95] interval (in bits)."""
    s = torch.maximum(q[:, 0] - y, y - q[:, 4]).sort().values; m = len(s); k = min(m, math.ceil((1 - alpha) * (m + 1))); return float(s[k - 1])


def maha_fit(X):
    mu = X.mean(0); C = torch.cov(X.T.double()) + 1e-3 * torch.eye(X.shape[1], **T64); return mu.double(), torch.linalg.inv(C)


def maha(X, mu, Ci): d = X.double() - mu; return ((d @ Ci) * d).sum(1)


# ---------------------------------------------------------------- fit stage
def stage_fit(args):
    ledger_t = time.time(); tr = load('train'); va = load('val'); ca = load('cal'); au = [audit_prior(tr, TRAIN, 'train'), audit_prior(va, VAL, 'val')]
    assert set(ca['pid'].tolist()) <= set(VAL) and (col(ca, 'fam') == 5).all(); log('data', len(tr['pid']), len(va['pid']), len(ca['pid']), au)
    st = Std(tr); Btr, Bva, Bca = to_dev(tr, st), to_dev(va, st), to_dev(ca, st); Y3 = lambda B: B['Y'][:, [0, 2, 4]]
    res = dict(NOT_CITABLE='until a blind bug review', code_sha256=CODE_SHA256, audit=au, n=dict(train=len(tr['pid']), val=len(va['pid']), cal=len(ca['pid'])), models={})
    nets = {}
    for kind, (ep, pat, lr, bs) in [x for x in (('D1', (args.ep1, 25, 2e-3, 64)), ('D2', (args.ep2, 6, 1e-3, 32))) if x[0] in KINDS]:
        ms, vb = [], []; t1 = time.time()
        for sd in range(3):
            net, v, e = fit_member(kind, Btr, Bva, Y3(Btr)[:, :2] if kind == 'D1' else Y3(Btr), Y3(Bva)[:, :2] if kind == 'D1' else Y3(Bva), 1000 * (kind == 'D2') + sd, ep, pat, lr, bs); ms.append(net); vb.append((v, e))
            log(f'{kind} member {sd}: val pinball (N+O, /{SC}) {v:.4f} after {e} epochs ({time.time() - t1:.0f}s)')
        nets[kind] = ms; qv, spv = ens_predict(ms, Bva); qc, spc = ens_predict(ms, Bca)
        qv, qc = qv * SC, qc * SC; yv, yc = va['Y'][:, [0, 2]], ca['Y'][:, [0, 2]]
        pb_val = float(pinball(qv[:, :2] / SC, torch.as_tensor(yv, dtype=torch.float32, device=DEV) / SC).sum())
        corr = [cqr_correction(qc[:, j], torch.as_tensor(yc[:, j], dtype=torch.float32, device=DEV)) for j in range(2)]
        cov_raw = [float(((torch.as_tensor(yc[:, j], dtype=torch.float32, device=DEV) >= qc[:, j, 0]) & (torch.as_tensor(yc[:, j], dtype=torch.float32, device=DEV) <= qc[:, j, 4])).float().mean()) for j in range(2)]
        spread_thr = float(torch.quantile(spv, 0.95))
        res['models'][kind] = dict(members=[dict(val_pinball=v, epochs=e) for v, e in vb], ensemble_val_pinball_NO=pb_val, cqr_correction_bits=dict(N=corr[0], O=corr[1]), cal_coverage_raw=dict(N=cov_raw[0], O=cov_raw[1]), cal_n=len(ca['pid']),
                                   spread_thr95=spread_thr, train_seconds=time.time() - t1)
        res['models'][kind]['spread_val_median_bits'] = float(spv.median() * SC)
    mu, Ci = maha_fit(Btr['X1']); dv = maha(Bva['X1'], mu, Ci); res['maha_thr95'] = float(torch.quantile(dv, 0.95)); res['primary'] = min(KINDS, key=lambda k: res['models'][k]['ensemble_val_pinball_NO'])
    log('primary (lower in-prior validation pinball):', res['primary'], {k: res['models'][k]['ensemble_val_pinball_NO'] for k in res['models']})
    torch.save(dict(nets={k: [n.state_dict() for n in v] for k, v in nets.items()}, std=dict(mx=st.mx, sx=st.sx, mp=st.mp, sp=st.sp, mt=st.mt, st=st.st), maha=(mu, Ci), res=res), OUT / f'models{SUF}.pt')
    res['wall_s'] = time.time() - ledger_t; jdump(OUT / f'fit_summary{SUF}.json', res); log('fit done')


