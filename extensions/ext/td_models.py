def stage_controls(args):
    M, nets = load_models(); res0 = M['res']; st = StdFrom(M['std']); tr = load('train'); va = load('val'); te = load('test'); Btr, Bva = to_dev(tr, st), to_dev(va, st); fams = col(te, 'fam'); mk = np.where(fams == 2)[0]
