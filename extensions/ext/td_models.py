def load(kind):
    fs = sorted(glob.glob(str((TESTBASE if (TESTBASE and kind in ('test', 'r4test')) else CELLS) / kind / '*.npz'))); assert fs, f'no shards in {kind}'; Z = [np.load(f) for f in fs]
