def stage_curve(args):
    """DESCRIPTIVE learning curve (run AFTER the pre-registered verdict; decides nothing): D1 trained on a random 1/8, 1/4, 1/2, all of the training cells (3 members, same hyper-parameters, early stopping on validation),
    point error of the median on the six F1 cells of R0 / R2 / R3 and its ratio to the better of A1 and A4. Reads the test shards only for this descriptive curve."""
    tr = load('train'); va = load('val'); te = load('test'); st = Std(tr); Btr, Bva, Bte = to_dev(tr, st), to_dev(va, st), to_dev(te, st); fams = col(te, 'fam'); out = dict(NOT_CITABLE='until a blind bug review', arms_inputs=ARMSMODE, curve={})
    g = torch.Generator(device=DEV); g.manual_seed(5); perm = torch.randperm(len(tr['pid']), generator=g, device=DEV)
    for frac in (0.125, 0.25, 0.5, 1.0):
        n = int(frac * len(perm)); ix = perm[:n]; b = sub(Btr, ix); y = Btr['Y'][ix][:, [0, 2]]; qs = []
        for sd in range(3): net, v, e = fit_member('D1', b, Bva, y, Bva['Y'][:, [0, 2]], 300 + sd, args.ep1, 25, 2e-3, 64); qs.append(predict(net, Bte)[:, 0] * SC)
        q = torch.stack(qs).mean(0).cpu().numpy(); res = {}
        for code, fam in ((2, 'R0'), (3, 'R2'), (4, 'R3')):
            mk = np.where(fams == code)[0]; d = {kk: (v[mk] if isinstance(v, np.ndarray) else v) for kk, v in te.items()}; d['mn'] = te['mn']; six = cellinfo(d)['six']; B = Bt(TEST, d['pid']); YN = d['Y'][:, 0]
            em, _ = B.pm(np.abs(q[mk, 2] - YN), six); e1, _ = B.pm(np.abs(d['BL'][:, 0] - YN), six); e4, _ = B.pm(np.abs(d['BL'][:, 2] - YN), six)
